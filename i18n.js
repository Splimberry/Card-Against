  function normalizeLanguage(language) {
    const value = languageAliases[String(language || "").trim()] || String(language || "").trim();
    return supportedLanguages[value] ? value : defaultLanguage;
  }

  function simplifyChineseText(text) {
    return Array.from(String(text || ""), (character) => simplifiedCharacterMap[character] || character).join("");
  }

  function localizeOutput(text, language = currentLanguage) {
    return language === "zh-Hans" ? simplifyChineseText(text) : text;
  }

